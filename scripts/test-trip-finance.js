const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const server=fs.readFileSync(require('node:path').join(__dirname,'../backend/server.js'),'utf8');
const start=server.indexOf('const TRIP_COST_FIELDS =');
const end=server.indexOf("router.get('/trip-finance'",start);
assert(start>=0&&end>start,'trip finance routines exist');
const sandbox={cleanString:x=>String(x??'').trim(),branchFields:b=>({branch_id:b.id}),nowIso:()=> '2026-09-23T00:00:00Z'};
vm.createContext(sandbox);
vm.runInContext(server.slice(start,end),sandbox);
const {tripMoney,tripPayload,tripSummary}=vm.runInContext('({tripMoney,tripPayload,tripSummary})',sandbox);
assert.equal(tripMoney('14.50'),1450);assert.equal(tripMoney(''),0);assert.throws(()=>tripMoney('-1'),/จำนวนเงิน/);assert.throws(()=>tripMoney('1.234'),/จำนวนเงิน/);
const vehicle={_id:'vehicle-1',plate_no:'72-5263'};
const payload=tripPayload({date:'2026-09-23',material:'ทราย',income_baht:'4763',sand_cost:'2100',stone_cost:'300',fuel_cost:'1200',tire_cost:'100',parts_cost:'0',mechanic_cost:'0',driver_cost:'200',other_cost:'0',distance_km:'105'},vehicle,{id:'branch-1'},{id:'owner-1'});
assert.equal(payload.income_satang,476300);assert.equal(payload.expense_satang,390000);assert.equal(payload.profit_satang,86300);assert.equal(payload.distance_km,105);
assert.throws(()=>tripPayload({date:'2026-02-31',material:'หิน',income_baht:'10'},vehicle,{id:'branch-1'},{id:'owner-1'}),/วันที่/);
const report=tripSummary([payload,{...payload,date:'2026-10-01',income_satang:10000,expense_satang:11000,profit_satang:-1000}], [vehicle]);
assert.equal(report.total.trips,2);assert.equal(report.total.income_satang,486300);assert.equal(report.total.profit_satang,85300);assert.equal(report.by_month.length,2);
console.log('Trip finance tests: PASS (money precision, cost categories, profit, invalid date, annual/monthly/vehicle totals)');
